import { app, isStatic, needsServer, route } from './core.js';

route('about', () => {
  app().innerHTML = `
  <h1 class="glow">About</h1>
  <p class="lead">Web MicroView is a microscopy image viewer and analysis dashboard. It started as a Bokeh server app
    (<span class="mono">app.py</span>); this web interface brings the same features to any browser, including a static site
    that needs no Python at all.</p>
  <h2>Two front ends, one set of functions</h2>
  <div class="two">
    <div class="panel"><h3>Bokeh dashboard (original)</h3>
      <p>Image View tab: TIFF upload, frame slider, gamma (contrast) slider, ROI box selection with a zoomed ROI view and a
        statistics bar chart; a channel selector for RGB files. Metadata tab: shape, data type, value range and the TIFF tags. The line-profile toggle is a
        placeholder there.</p>
      <pre>pip install -r requirements.txt
bokeh serve app.py
# open http://localhost:5006/app</pre></div>
    <div class="panel"><h3>Web app (this site)</h3>
      <p>The viewer runs in the browser: a pure-JS TIFF reader and <span class="mono">image_math.js</span>, a port of the repo's
        <span class="mono">image_utils.py</span> tested against it. Adds a working line profile, playback, lookup tables,
        ROI mean over frames, physical units and CSV/PNG export.</p>
      <pre>pip install -r requirements-web.txt
python run_web.py
# open http://127.0.0.1:8136</pre></div>
  </div>
  ${isStatic() ? needsServer('Reading metadata with tifffile and decoding files the browser reader cannot handle') : ''}
  <h2>Conventions</h2>
  <ul>
    <li>Pixel coordinates start at the top-left corner of the image (pixel (x, y) covers x to x+1, y to y+1), with row 0 at the top, as in ImageJ/Fiji.</li>
    <li>ROI boxes drawn with the mouse snap to pixel edges. Standard deviation is the population value (numpy's default).</li>
    <li>Display: each frame is scaled to its own min-max and then raised to 1/gamma (as the Bokeh app); optionally one range for the whole stack.</li>
    <li>Line profiles are bilinearly interpolated, with about one sample per pixel of length.</li>
    <li>Physical units are shown only when the file itself declares a pixel size (OME-XML PhysicalSizeX, or ImageJ unit + XResolution);
      otherwise everything stays in pixels and the viewer says so.</li>
    <li>Multi-page files are read page by page in file order; ImageJ/OME channels and z-slices appear as frames.
      RGB and other multi-sample images get a channel selector.</li>
  </ul>
  <h2>Credits</h2>
  <p>By George Dickinson (<a href="https://github.com/gddickinson/web_microview">gddickinson/web_microview</a>), MIT licence.
    Built with AI assistance from Claude (Anthropic). The demo stack is synthetic, generated by
    <span class="mono">scripts/make_demo.py</span>.</p>`;
});
